#!/usr/bin/env python3
"""Orb Hunter: src/world_data.c from the Amiga original's own levels.c.

The original builds its world at start-up (levels.c levels_init: 8 x 6 rooms
of 20 x 16 tiles from a hash, plus place_items). This compiles that file on
the host with a stub <exec/types.h>, runs levels_init() and writes:

- the 48 rooms, run-length coded a room at a time (a byte: count << 4 |
  tile, count 1..15) with each room's offset (1.5 KB instead of 15 KB)
- the item table (g_items: room, tile, type), as place_items() leaves it

The original is found at $ORB_HUNTER_SRC or
~/code/claude_world/amiga_mcp/examples/orb_hunter (amiga_games). Needs a
host C compiler (cc). Run: python3 tools/gen_world.py [--bin out.bin]
(--bin also writes the raw 15,360-byte world, which the test compares
rooms against).
"""
import os
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
ORIG = Path(os.environ.get("ORB_HUNTER_SRC",
                           Path.home() / "code/claude_world/amiga_mcp/examples/orb_hunter"))

STUB = r"""
#ifndef EXEC_TYPES_H
#define EXEC_TYPES_H
#include <stdint.h>
typedef int32_t LONG; typedef uint32_t ULONG; typedef int16_t WORD;
typedef uint16_t UWORD; typedef int8_t BYTE; typedef uint8_t UBYTE;
#endif
"""
DUMP = r"""
#include <stdio.h>
#include "game.h"
int main(void)
{
    WORD i;
    levels_init();
    fwrite(world_rooms, 1, sizeof world_rooms, stdout);
    for (i = 0; i < g_num_items; i++)
        printf("%c%c%c%c%c", g_items[i].room_x, g_items[i].room_y,
               g_items[i].tile_x, g_items[i].tile_y, g_items[i].type);
    return 0;
}
"""


def original_world():
    """(world bytes (48 * 320, room (x, y) at (y * 8 + x) * 320), items)"""
    with tempfile.TemporaryDirectory() as td:
        t = Path(td)
        (t / "exec").mkdir()
        (t / "exec" / "types.h").write_text(STUB)
        (t / "dump.c").write_text(DUMP)
        exe = t / "dump"
        subprocess.run(["cc", "-O1", "-w", f"-I{t}", f"-iquote{ORIG}", "-o", str(exe),
                        str(t / "dump.c"), str(ORIG / "levels.c")], check=True)
        out = subprocess.run([str(exe)], check=True, capture_output=True).stdout
    # levels.c: world_rooms[WORLD_H][WORLD_W][ROOM_H][ROOM_W] = room (x, y) at (y * 8 + x)
    world = out[:48 * 320]
    rest = out[48 * 320:]
    items = [tuple(rest[i:i + 5]) for i in range(0, len(rest), 5)]
    return world, items


def main():
    world, items = original_world()
    rle, offs = [], []
    for r in range(48):
        tiles = world[r * 320:(r + 1) * 320]
        offs.append(len(rle))
        i = 0
        while i < 320:
            t, n = tiles[i], 1
            while i + n < 320 and tiles[i + n] == t and n < 15:
                n += 1
            rle.append((n << 4) | t)
            i += n
    o = ["/* generated by tools/gen_world.py from the original's levels.c - do not edit */",
         '#include "game.h"', "",
         "/* the 48 rooms (room (x, y) is y * 8 + x), run-length coded: count << 4 | tile */",
         f"const uint8_t world_rle[{len(rle)}] = {{"]
    for i in range(0, len(rle), 20):
        o.append("    " + ", ".join(str(v) for v in rle[i:i + 20]) + ",")
    o.append("};")
    o.append("const uint16_t world_off[48] = {")
    for i in range(0, 48, 12):
        o.append("    " + ", ".join(str(v) for v in offs[i:i + 12]) + ",")
    o.append("};")
    o.append("")
    o.append("/* place_items(): room x, y, tile x, y, type, collected */")
    o.append(f"const ItemSpawn items_start[{len(items)}] = {{")
    for it in items:
        o.append("    { %d, %d, %d, %d, %d, 0 }," % it)
    o.append("};")
    o.append(f"const uint8_t items_count = {len(items)};")
    (HERE / "src" / "world_data.c").write_text("\n".join(o) + "\n")
    print(f"world: {len(world)} bytes -> {len(rle)} run-length coded; {len(items)} items")
    if "--bin" in sys.argv:
        Path(sys.argv[sys.argv.index("--bin") + 1]).write_bytes(world)


if __name__ == "__main__":
    main()
